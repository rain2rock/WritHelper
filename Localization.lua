local function language()
  local selected = WritHelperDB and WritHelperDB.language or 'auto'
  if selected == 'ru' or selected == 'en' or selected == 'zh' then return selected end
  local locale = GetLocale and GetLocale() or 'ruRU'
  if locale == 'ruRU' then return 'ru' end
  if locale == 'zhCN' or locale == 'zhTW' then return 'zh' end
  return 'en'
end
function WritHelperTranslate(key)
  local lang = language()
  local entry = translations[key]
  return lang == 'ru' and key or (entry and entry[lang]) or key
end
